"""
Per-rater prior persuasiveness of the frozen A_gc arguments — the un-averaged precursor of Table 2.

Answers a reviewer's question about whether the pro and con sides of A_gc are balanced: it shows
every LLM expert's raw 1-7 rating of every argument, before any averaging.

Which columns are A_gc: `data/persuasiveness_scores.csv` holds three argument sets side by side
(gpt-, sonnet- and devstral-generated, 10 each) rated by 3 LLMs and 4 humans. The paper's frozen set
was generated by claude-sonnet-4, so A_gc is the **sonnet_** block — verified by locating the frozen
ARGS inside the source notebook's flat 30-argument list, where they occupy positions 10..19, i.e.
the second block, in a1..a10 order. The humans were only asked about that block, which is a second
sign it is the set the study kept.

    PYTHONPATH=src /opt/anaconda3/bin/python docs/make_table_persuasiveness.py
        -> docs/table_persuasiveness_Agc.{csv,md,tex,png,pdf}
"""
from __future__ import annotations

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import mannwhitneyu

HERE = Path(__file__).parent
ROOT = HERE.parent
SRC = ROOT / "paper_reproduction" / "s5_epistemic_networks" / "data" / "persuasiveness_scores.csv"

BLOCK = "sonnet"                      # the frozen A_gc set
LLMS = [("anthropic/claude-sonnet-4", "claude-sonnet-4"),
        ("openai/gpt-4.1", "gpt-4.1"),
        ("mistralai/devstral-medium", "devstral-medium")]
HUMANS = ["derzhiarbuz@gmail.com", "na.km1973@gmail.com",
          "stilusha@gmail.com", "author@gmail.com"]
SERIF = {"family": "DejaVu Serif"}
INK = "#1b2733"


def load():
    df = pd.read_csv(SRC)
    cols = ([f"{BLOCK}_pro{k}" for k in range(1, 6)] +
            [f"{BLOCK}_con{k}" for k in range(1, 6)])
    labels = [f"a{i}" for i in range(1, 11)]
    out = {}
    for subj, name in LLMS:
        row = df[df.subject == subj]
        out[name] = [int(row[c].iloc[0]) for c in cols]
    hum = np.array([[int(df[df.subject == h][c].iloc[0]) for c in cols] for h in HUMANS])
    return pd.DataFrame(out, index=labels), hum


def main():
    T, hum = load()
    T.insert(0, "valence", ["pro"] * 5 + ["con"] * 5)
    T["LLM mean"] = T[[n for _, n in LLMS]].mean(axis=1).round(2)
    T["human mean"] = hum.mean(0).round(2)

    T.to_csv(HERE / "table_persuasiveness_Agc.csv", index_label="argument")

    # ── balance check, per rater ────────────────────────────────────────────────
    print("Prior persuasiveness of A_gc, 1–7, per rater (un-averaged)\n")
    print(T.to_string())
    print("\npro vs con, per rater:")
    lines = []
    for _, name in LLMS:
        v = T[name].to_numpy()
        p = mannwhitneyu(v[:5], v[5:]).pvalue
        lines.append((name, v[:5].mean(), v[5:].mean(), p))
        print(f"  {name:18s} pro {v[:5].mean():.2f}  con {v[5:].mean():.2f}  "
              f"diff {v[:5].mean()-v[5:].mean():+.2f}  Mann-Whitney P = {p:.3f}")
    allv = T[[n for _, n in LLMS]].to_numpy()
    p_all = mannwhitneyu(allv[:5].ravel(), allv[5:].ravel()).pvalue
    print(f"  {'all three pooled':18s} pro {allv[:5].mean():.2f}  con {allv[5:].mean():.2f}  "
          f"diff {allv[:5].mean()-allv[5:].mean():+.2f}  Mann-Whitney P = {p_all:.3f}")
    hp = mannwhitneyu(hum[:, :5].ravel(), hum[:, 5:].ravel()).pvalue
    print(f"  {'humans (n=4)':18s} pro {hum[:, :5].mean():.2f}  con {hum[:, 5:].mean():.2f}  "
          f"diff {hum[:, :5].mean()-hum[:, 5:].mean():+.2f}  Mann-Whitney P = {hp:.3f}")
    print(f"\nrange over all 30 LLM ratings: {allv.min()}–{allv.max()} on a 1–7 scale")

    # ── LaTeX ──────────────────────────────────────────────────────────────────
    tex = [r"\begin{table}[t!]", r"\centering",
           r"\caption{Prior persuasiveness of the $\mathcal{A}_{\mathrm{gc}}$ arguments, "
           r"rated 1--7 by each LLM expert (individual ratings, before averaging).}",
           r"\label{tab:persuasiveness-raw}",
           r"% integer ratings and 2-decimal means share these columns, so 1.2 for all of them",
           r"\sisetup{table-number-alignment=center}",
           r"\begin{tabular}{l l S[table-format=1.2] S[table-format=1.2] "
           r"S[table-format=1.2] S[table-format=1.2]}", r"\toprule",
           r" & & \multicolumn{3}{c}{LLM expert} & \\", r"\cmidrule(lr){3-5}",
           r"Argument & Valence & {\textit{claude-sonnet-4}} & {\textit{gpt-4.1}} & "
           r"{\textit{devstral-medium}} & {Mean} \\", r"\midrule"]
    for i, lab in enumerate(T.index):
        if i == 5:
            tex.append(r"\addlinespace")
        vals = " & ".join(str(T[n].iloc[i]) for _, n in LLMS)
        tex.append(f"$a_{{{i+1}}}$ & {T['valence'].iloc[i]} & {vals} & {T['LLM mean'].iloc[i]:.2f} \\\\")
    tex += [r"\midrule",
            f"\\multicolumn{{2}}{{l}}{{Mean, pro ($a_1$--$a_5$)}} & "
            + " & ".join(f"{T[n][:5].mean():.2f}" for _, n in LLMS)
            + f" & {allv[:5].mean():.2f} \\\\",
            f"\\multicolumn{{2}}{{l}}{{Mean, con ($a_6$--$a_{{10}}$)}} & "
            + " & ".join(f"{T[n][5:].mean():.2f}" for _, n in LLMS)
            + f" & {allv[5:].mean():.2f} \\\\",
            r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (HERE / "table_persuasiveness_Agc.tex").write_text("\n".join(tex) + "\n")

    # ── markdown ───────────────────────────────────────────────────────────────
    md = ["| Argument | Valence | claude-sonnet-4 | gpt-4.1 | devstral-medium | LLM mean | human mean |",
          "|---|---|---|---|---|---|---|"]
    for i, lab in enumerate(T.index):
        md.append(f"| {lab} | {T['valence'].iloc[i]} | "
                  + " | ".join(str(T[n].iloc[i]) for _, n in LLMS)
                  + f" | {T['LLM mean'].iloc[i]:.2f} | {T['human mean'].iloc[i]:.2f} |")
    md.append(f"| **mean pro** | | " + " | ".join(f"{T[n][:5].mean():.2f}" for _, n in LLMS)
              + f" | {allv[:5].mean():.2f} | {hum[:, :5].mean():.2f} |")
    md.append(f"| **mean con** | | " + " | ".join(f"{T[n][5:].mean():.2f}" for _, n in LLMS)
              + f" | {allv[5:].mean():.2f} | {hum[:, 5:].mean():.2f} |")
    (HERE / "table_persuasiveness_Agc.md").write_text("\n".join(md) + "\n")

    # ── picture ────────────────────────────────────────────────────────────────
    x = [0.03, 0.20, 0.40, 0.575, 0.755, 0.925]
    fig, ax = plt.subplots(figsize=(10.4, 6.6))
    ax.set_xlim(0, 1); ax.set_ylim(0, 1); ax.axis("off")
    FS = 12.5
    ax.text(0.5, 0.975, "Prior persuasiveness of the $\\mathcal{A}_{\\mathrm{gc}}$ arguments "
                        "(1–7), per LLM expert", ha="center", va="center", fontsize=FS + 1, **SERIF)
    ax.hlines(0.935, 0.01, 0.99, color=INK, lw=1.5)
    ax.text((x[2] + x[4]) / 2, 0.898, "LLM expert", ha="center", va="center", fontsize=FS, **SERIF)
    ax.hlines(0.866, x[2] - 0.085, x[4] + 0.085, color=INK, lw=0.9)
    for xi, lab, ha in ((x[0], "Argument", "left"), (x[1], "Valence", "left"),
                        (x[2], "claude-sonnet-4", "center"), (x[3], "gpt-4.1", "center"),
                        (x[4], "devstral-medium", "center"), (x[5], "Mean", "center")):
        ax.text(xi, 0.828, lab, ha=ha, va="center", fontsize=FS - 0.5,
                style="italic" if ha == "center" and lab != "Mean" else "normal", **SERIF)
    ax.hlines(0.792, 0.01, 0.99, color=INK, lw=1.5)
    y = 0.752
    for i, lab in enumerate(T.index):
        if i == 5:
            y -= 0.022
        ax.text(x[0], y, f"$a_{{{i+1}}}$", ha="left", va="center", fontsize=FS, **SERIF)
        ax.text(x[1], y, T["valence"].iloc[i], ha="left", va="center", fontsize=FS, **SERIF)
        for xi, (_, n) in zip(x[2:5], LLMS):
            ax.text(xi, y, str(T[n].iloc[i]), ha="center", va="center", fontsize=FS, **SERIF)
        ax.text(x[5], y, f"{T['LLM mean'].iloc[i]:.2f}", ha="center", va="center",
                fontsize=FS, **SERIF)
        y -= 0.056
    ax.hlines(y + 0.024, 0.01, 0.99, color=INK, lw=0.9)
    y -= 0.022
    for lbl, sl in (("Mean, pro ($a_1$–$a_5$)", slice(0, 5)),
                    ("Mean, con ($a_6$–$a_{10}$)", slice(5, 10))):
        ax.text(x[0], y, lbl, ha="left", va="center", fontsize=FS, **SERIF)
        for xi, (_, n) in zip(x[2:5], LLMS):
            ax.text(xi, y, f"{T[n][sl].mean():.2f}", ha="center", va="center", fontsize=FS, **SERIF)
        ax.text(x[5], y, f"{allv[sl].mean():.2f}", ha="center", va="center", fontsize=FS, **SERIF)
        y -= 0.056
    ax.hlines(y + 0.030, 0.01, 0.99, color=INK, lw=1.5)
    ax.text(0.01, y - 0.010, "All 30 ratings fall in 4–6 on the 1–7 scale; pro and con sides do not "
            f"differ (pooled Mann–Whitney $P$ = {p_all:.2f}).",
            ha="left", va="top", fontsize=FS - 3, color="#4a5a68", **SERIF)
    for ext in ("png", "pdf"):
        fig.savefig(HERE / f"table_persuasiveness_Agc.{ext}", dpi=300, bbox_inches="tight",
                    facecolor="white")
    plt.close(fig)
    print("\nwrote docs/table_persuasiveness_Agc.{csv,md,tex,png,pdf}")


if __name__ == "__main__":
    main()
